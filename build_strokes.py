"""
Build public/strokes/<code>.json from the official KanjiVG release.

Each file holds the stroke paths in writing order and the stroke-number positions:
    {"s": ["M29.5,17.25c3.5,3…", …], "n": [[20.25, 13.63], …]}

KanjiVG (https://kanjivg.tagaini.net) is © Ulrich Apel, licensed CC BY-SA 3.0.
The generated files keep that licence; see public/strokes/LICENSE.txt.

Usage:  python build_strokes.py [release-tag]     (defaults to the latest release)
"""
import io
import json
import re
import sys
import urllib.request
import zipfile
from pathlib import Path

sys.stdout.reconfigure(encoding='utf-8')

ROOT = Path(__file__).resolve().parent
DATASET = ROOT / 'src' / 'data' / 'kanji_data.json'
OUT_DIR = ROOT / 'public' / 'strokes'
HEADERS = {'User-Agent': 'kanji-helper-build'}

PATH_RE = re.compile(r'<path\b[^>]*\bid="kvg:[0-9a-f]+(?:-[A-Za-z0-9]+)*-s(\d+)"[^>]*\bd="([^"]+)"')
# Stroke numbers are written as transform="matrix(1 0 0 1 x y)" (space separated)
TEXT_RE = re.compile(r'<text\b[^>]*\btransform="matrix\(([^)]+)\)"[^>]*>\s*(\d+)\s*</text>')


def fetch(url: str) -> bytes:
    with urllib.request.urlopen(urllib.request.Request(url, headers=HEADERS)) as resp:
        return resp.read()


def release_zip_url(tag: str | None) -> tuple[str, str]:
    api = 'https://api.github.com/repos/KanjiVG/kanjivg/releases/' + (f'tags/{tag}' if tag else 'latest')
    release = json.loads(fetch(api))
    for asset in release['assets']:
        if asset['name'].endswith('-main.zip'):
            return release['tag_name'], asset['browser_download_url']
    raise SystemExit(f'No *-main.zip asset in release {release["tag_name"]}')


def parse(svg: str) -> dict:
    strokes = sorted((int(n), d) for n, d in PATH_RE.findall(svg))
    numbers: list[list[float] | None] = [None] * len(strokes)
    for matrix, label in TEXT_RE.findall(svg):
        parts = [float(v) for v in re.split(r'[\s,]+', matrix.strip())]
        idx = int(label) - 1
        if len(parts) == 6 and 0 <= idx < len(numbers):
            numbers[idx] = [round(parts[4], 2), round(parts[5], 2)]
    return {'s': [d for _, d in strokes], 'n': numbers}


def main() -> None:
    kanji = json.loads(DATASET.read_text(encoding='utf-8'))
    tag, url = release_zip_url(sys.argv[1] if len(sys.argv) > 1 else None)
    print(f'KanjiVG {tag}: downloading {url}')
    archive = zipfile.ZipFile(io.BytesIO(fetch(url)))
    members = {Path(name).stem: name for name in archive.namelist() if name.endswith('.svg')}

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for old in OUT_DIR.glob('*.json'):
        old.unlink()

    missing, mismatched, written = [], [], 0
    for k in kanji:
        member = members.get(k['code'])
        if not member:
            missing.append(k['c'])
            continue
        data = parse(archive.read(member).decode('utf-8'))
        if not data['s']:
            missing.append(k['c'])
            continue
        if len(data['s']) != k['st']:
            mismatched.append(f"{k['c']} ({len(data['s'])} vs {k['st']})")
        (OUT_DIR / f"{k['code']}.json").write_text(json.dumps(data, separators=(',', ':')), encoding='utf-8')
        written += 1

    (OUT_DIR / 'LICENSE.txt').write_text(
        f'Stroke data derived from KanjiVG {tag} (https://kanjivg.tagaini.net),\n'
        'Copyright (C) Ulrich Apel. Licensed under Creative Commons Attribution-Share Alike 3.0\n'
        '(https://creativecommons.org/licenses/by-sa/3.0/).\n'
        'Generated by build_strokes.py: paths and stroke-number positions only, unchanged.\n',
        encoding='utf-8',
    )

    print(f'Wrote {written} files to {OUT_DIR.relative_to(ROOT)}')
    print(f'Missing from KanjiVG ({len(missing)}): {" ".join(missing) or "none"}')
    print(f'Stroke count differs from dataset ({len(mismatched)}): {", ".join(mismatched) or "none"}')


if __name__ == '__main__':
    main()
